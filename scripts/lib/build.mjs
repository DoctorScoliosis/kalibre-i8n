import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { flattenLocale } from "./integrity.mjs";

const sha256 = (content) => crypto.createHash("sha256").update(content).digest("hex");

// Read only message files. flattenLocale handles nested objects, arrays, and translator-only _notes.
// Coverage measures non-empty message-key presence, not wording quality or native-speaker review.
function readContentStrings(dir) {
  const files = fs.readdirSync(dir)
    .filter((file) => file.endsWith(".json") && file !== "meta.json" && file !== "manifest.json")
    .sort();
  return Object.fromEntries(files.map((file) => [
    file.replace(/\.json$/, ""),
    JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"))
  ]));
}

function nonEmptyMessageKeys(strings) {
  const { messages } = flattenLocale(strings);
  return new Set([...messages]
    .filter(([, text]) => typeof text === "string" && text.trim().length > 0)
    .map(([key]) => key));
}

function translationProgress(strings, canonicalKeys) {
  const { messages } = flattenLocale(strings);
  const translatedMessages = [...messages]
    .filter(([key, text]) => canonicalKeys.has(key) && typeof text === "string" && text.trim().length > 0)
    .length;
  return { translatedMessages, totalMessages: canonicalKeys.size };
}

// A locale is published unless its meta.json says `"published": false`. An unpublished locale keeps its
// files here (its partial translation is work to come) but gets no manifest, no pack and no entry in
// index.json, so the application never offers it.
export const isPublished = (meta) => meta?.published !== false;

// The contributor-facing coverage table (Kalibre LOCALISATION-PLAN L11, D369): one row per published
// translation with its progress bar, exact percentage, messages still in English and review status.
// It is generated from index.json, so it can never disagree with what the application shows.
export const COVERAGE_START = "<!-- coverage:start (generated by npm run build; do not edit) -->";
export const COVERAGE_END = "<!-- coverage:end -->";

const flagOf = (id) => {
  const region = id.split("-")[1];
  return region && /^[A-Z]{2}$/.test(region)
    ? String.fromCodePoint(...[...region].map((c) => 0x1F1E6 + c.charCodeAt(0) - 65))
    : "🌐";
};

export function coverageTable(locales) {
  const rows = locales
    .filter((entry) => entry.id !== "en-GB" && entry.translationProgress?.totalMessages > 0)
    .map((entry) => {
      const { translatedMessages, totalMessages } = entry.translationProgress;
      const percent = Math.floor(translatedMessages * 100 / totalMessages);
      const filled = Math.floor(percent / 10);
      const bar = "█".repeat(filled) + "░".repeat(10 - filled);
      const remaining = (totalMessages - translatedMessages).toLocaleString("en-GB");
      return `| ${flagOf(entry.id)} ${entry.name} | ${entry.englishName} | \`${entry.id}\` | ${bar} ${percent}% | ${translatedMessages.toLocaleString("en-GB")} / ${totalMessages.toLocaleString("en-GB")} | ${remaining} | ${entry.reviewed} |`;
    });
  return [
    "| Language | In English | Code | Progress | Translated | Still in English | Reviewed |",
    "|---|---|---|---|---|---|---|",
    ...rows
  ].join("\n");
}

// Writes the table between the README's markers; a README without them is left alone.
export function writeCoverageTable(rootDir, locales) {
  const readmePath = path.join(rootDir, "README.md");
  if (!fs.existsSync(readmePath)) return false;
  const readme = fs.readFileSync(readmePath, "utf8");
  const start = readme.indexOf(COVERAGE_START);
  const end = readme.indexOf(COVERAGE_END);
  if (start < 0 || end < start) return false;
  const next = `${readme.slice(0, start + COVERAGE_START.length)}\n${coverageTable(locales)}\n${readme.slice(end)}`;
  if (next !== readme) fs.writeFileSync(readmePath, next);
  return true;
}

// Bundles every published locale's modular files into manifest.json, a pack and an index.json entry.
// Only the generated artefacts are written; nothing here is meant to be edited by hand.
export function buildPacks({ rootDir }) {
  const localesDir = path.join(rootDir, "locales");
  const packsDir = path.join(rootDir, "packs");
  fs.mkdirSync(packsDir, { recursive: true });

  const canonicalDir = path.join(localesDir, "en-GB");
  if (!fs.existsSync(canonicalDir)) throw new Error("Cannot calculate translation progress: missing locales/en-GB");
  const canonicalKeys = nonEmptyMessageKeys(readContentStrings(canonicalDir));

  const localeDirs = fs.readdirSync(localesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name);

  const indexLocales = [];
  const skipped = [];
  const unpublished = [];

  for (const tag of localeDirs) {
    const dir = path.join(localesDir, tag);
    const metaPath = path.join(dir, "meta.json");
    if (!fs.existsSync(metaPath)) {
      skipped.push(tag);
      continue;
    }
    const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
    if (!isPublished(meta)) {
      // Nothing is distributed for it, and anything an earlier build left behind goes.
      fs.rmSync(path.join(dir, "manifest.json"), { force: true });
      fs.rmSync(path.join(packsDir, `${tag}.json`), { force: true });
      unpublished.push(tag);
      continue;
    }
    const files = fs.readdirSync(dir)
      .filter((f) => f.endsWith(".json") && f !== "meta.json" && f !== "manifest.json")
      .sort();

    const fileChecksums = {};
    const strings = {};

    for (const f of files) {
      const content = fs.readFileSync(path.join(dir, f), "utf8");
      fileChecksums[f] = sha256(content);
      strings[f.replace(/\.json$/, "")] = JSON.parse(content);
    }

    // Write manifest.json
    const manifest = {
      kalibreLocale: 1,
      ...meta,
      files: fileChecksums
    };
    fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

    // Write pack
    const packContent = JSON.stringify({ meta, strings }, null, 2) + "\n";
    const packFile = `${tag}.json`;
    const packPath = path.join(packsDir, packFile);
    fs.writeFileSync(packPath, packContent);

    indexLocales.push({
      id: meta.id,
      name: meta.name,
      englishName: meta.englishName,
      dir: meta.dir || "ltr",
      fallback: meta.fallback,
      revision: meta.revision || 1,
      version: meta.version || "1.0.0",
      reviewed: meta.reviewed || "community",
      translationProgress: translationProgress(strings, canonicalKeys),
      changes: meta.changes || "",
      path: `locales/${tag}/manifest.json`,
      pack: `packs/${packFile}`,
      sha256: sha256(packContent),
      bytes: fs.statSync(packPath).size
    });
  }

  // Write index.json
  const index = {
    kalibreI18nIndex: 1,
    repository: {
      name: "kalibre-i8n",
      description: "Independent, versioned localisation packs for Kalibre.",
      url: "https://github.com/DoctorScoliosis/kalibre-i8n"
    },
    locales: indexLocales.sort((a, b) => a.id.localeCompare(b.id))
  };
  fs.writeFileSync(path.join(rootDir, "index.json"), JSON.stringify(index, null, 2) + "\n");
  writeCoverageTable(rootDir, index.locales);
  return { built: indexLocales.map((item) => item.id), skipped, unpublished };
}
